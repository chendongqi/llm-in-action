# ── Judge prompts ─────────────────────────────────────────────────────────────

PAIRWISE_JUDGE = """你是一个专业的技术内容评审员。
请判断以下两个回答中哪一个更好。

问题：{question}

回答 A：
{answer_a}

回答 B：
{answer_b}

请从准确性、完整性、清晰度三个维度综合评判。
只回答 "A" 或 "B"，选择你认为更好的那个。"""

SCORING_JUDGE = """你是一个技术内容评审员。
请对以下回答评分（1-10分）：

问题：{question}
回答：{answer}

评分维度：
- 准确性（4分）：技术内容是否正确
- 完整性（3分）：是否覆盖了关键要点
- 清晰度（3分）：是否易于理解

只返回一个整数分数（1-10），不要其他内容。"""


def judge_pairwise(question: str, answer_a: str, answer_b: str) -> str:
    """Returns 'A' or 'B'."""
    prompt = PAIRWISE_JUDGE.format(question=question, answer_a=answer_a, answer_b=answer_b)
    result = ask(prompt).strip().upper()
    return "A" if "A" in result and "B" not in result else "B" if "B" in result else "A"


def judge_score(question: str, answer: str) -> float:
    """Returns a score 1-10."""
    prompt = SCORING_JUDGE.format(question=question, answer=answer)
    result = ask(prompt).strip()
    match = re.search(r'\d+', result)
    return float(match.group()) if match else 5.0


# ── Experiment 1: Position Bias ───────────────────────────────────────────────

def experiment_position_bias(trials: int = 3) -> dict:
    """
    For each answer pair, judge it twice: A→B and B→A.
    Count how often the FIRST answer wins regardless of which answer it is.
    """
    first_wins = 0
    second_wins = 0
    total = 0

    results = []
    for pair in ANSWER_PAIRS:
        for _ in range(trials):
            # Order 1: A first
            winner_1 = judge_pairwise(pair["question"], pair["answer_a"], pair["answer_b"])
            # Order 2: B first (swapped)
            winner_2_raw = judge_pairwise(pair["question"], pair["answer_b"], pair["answer_a"])
            # Normalize: in order 2, "A" means the first answer shown (which is B)
            winner_2 = "B" if winner_2_raw == "A" else "A"

            # Did the first-presented answer win in order 1?
            if winner_1 == "A":  # A was shown first and won
                first_wins += 1
            else:
                second_wins += 1

            # Did the first-presented answer win in order 2?
            if winner_2_raw == "A":  # B was shown first (as "A"), and won
                first_wins += 1
            else:
                second_wins += 1

            total += 2
            results.append({
                "question": pair["question"][:30],
                "order1_winner": winner_1,
                "order2_winner": winner_2,
                "consistent": winner_1 == winner_2,
            })
            time.sleep(0.5)

    return {
        "first_position_win_rate": first_wins / total,
        "second_position_win_rate": second_wins / total,
        "consistency_rate": sum(1 for r in results if r["consistent"]) / len(results),
        "total_pairs": total // 2,
        "details": results,
    }


# ── Experiment 2: Verbosity Bias ──────────────────────────────────────────────

def experiment_verbosity_bias(trials: int = 3) -> dict:
    """
    Score a concise correct answer vs a verbose correct answer with same content.
    Measure the score delta.
    """
    concise_scores = []
    verbose_scores = []

    for case in VERBOSE_ANSWERS:
        for _ in range(trials):
            c_score = judge_score(case["question"], case["concise"])
            v_score = judge_score(case["question"], case["verbose"])
            concise_scores.append(c_score)
            verbose_scores.append(v_score)
            time.sleep(0.5)

    avg_concise = statistics.mean(concise_scores)
    avg_verbose = statistics.mean(verbose_scores)

    return {
        "avg_concise_score": round(avg_concise, 2),
        "avg_verbose_score": round(avg_verbose, 2),
        "verbosity_bonus": round(avg_verbose - avg_concise, 2),
        "individual_concise": concise_scores,
        "individual_verbose": verbose_scores,
    }


# ── Experiment 3: Self-Bias ───────────────────────────────────────────────────

def experiment_self_bias(trials: int = 3) -> dict:
    """
    Generate an answer with the model, then:
    - Evaluate with the SAME model (self-eval)
    - Evaluate with the SAME model but framed as independent (cross-eval)
    This tests whether the framing of 'I generated this' affects the score.

    Note: Since we only have one model available (glm-4-flash), we simulate
    self-bias by comparing two evaluation framings:
    Framing A: standard judge (treats as external content)
    Framing B: 'expert reviewer' framing (higher standards)
    """
    standard_scores = []
    expert_scores = []

    STANDARD_PROMPT = """评估以下技术回答的质量（1-10分），只返回数字：
问题：{question}
回答：{answer}"""

    EXPERT_PROMPT = """作为一位严格的高级工程师，请批判性地评估以下回答（1-10分），只返回数字：
问题：{question}
回答：{answer}
注意：普通水平的回答不超过 6 分，只有出色的回答才能得 8 分以上。"""

    test_cases = [
        {
            "question": "解释 Python 的 asyncio 工作原理",
            "answer": (
                "asyncio 基于事件循环（event loop）和协程（coroutine）。"
                "事件循环持续运行，监听 I/O 事件并调度就绪的协程。"
                "当协程遇到 `await` 时主动让出控制权，事件循环运行其他协程。"
                "本质是单线程的协作式多任务，适合 I/O 密集型并发。"
            ),
        },
        {
            "question": "Python 的 `yield` 和 `return` 有什么区别？",
            "answer": (
                "`return` 终止函数并返回值。`yield` 暂停函数并产出一个值，"
                "保留函数状态，下次调用从 yield 处继续。"
                "包含 `yield` 的函数是生成器，延迟计算，节省内存，"
                "适合处理大型序列或无限序列。"
            ),
        },
    ]

    for case in test_cases:
        for _ in range(trials):
            s_prompt = STANDARD_PROMPT.format(
                question=case["question"], answer=case["answer"])
            e_prompt = EXPERT_PROMPT.format(
                question=case["question"], answer=case["answer"])

            s_match = re.search(r'\d+', ask(s_prompt) or "5")
            e_match = re.search(r'\d+', ask(e_prompt) or "5")
            s_score = float(s_match.group() if s_match else "5")
            e_score = float(e_match.group() if e_match else "5")

            standard_scores.append(s_score)
            expert_scores.append(e_score)
            time.sleep(0.5)

    avg_standard = statistics.mean(standard_scores)
    avg_expert = statistics.mean(expert_scores)

    return {
        "avg_standard_score": round(avg_standard, 2),
        "avg_expert_score": round(avg_expert, 2),
        "framing_delta": round(avg_standard - avg_expert, 2),
        "note": "positive delta = standard prompt scores higher than expert prompt",
    }


# ── Main ──────────────────────────────────────────────────────────────────────

def main() -> None:
    print("\n" + "=" * WIDTH)
    print("LLM-as-Judge Bias Experiments")
    print("Model: glm-4-flash  |  Trials per case: 3")
    print("=" * WIDTH)

    # Experiment 1
    print(f"\n{'─' * WIDTH}")
    print("Experiment 1: Position Bias")
    print("Hypothesis: Judge favors whichever answer appears first")
    print(f"{'─' * WIDTH}")
    pos = experiment_position_bias(trials=3)
    print(f"\n  First-position win rate:  {pos['first_position_win_rate']:.0%}")
    print(f"  Second-position win rate: {pos['second_position_win_rate']:.0%}")
    print(f"  Consistency rate:         {pos['consistency_rate']:.0%}")
    print(f"  (unbiased baseline: 50% / 50% / 100%)")
    bias_magnitude = abs(pos['first_position_win_rate'] - 0.5)
    print(f"  Position bias magnitude:  {bias_magnitude:.0%} above 50% baseline")

    # Experiment 2
    print(f"\n{'─' * WIDTH}")
    print("Experiment 2: Verbosity Bias")
    print("Hypothesis: Judge gives higher scores to longer answers")
    print(f"{'─' * WIDTH}")
    verb = experiment_verbosity_bias(trials=3)
    print(f"\n  Avg concise answer score: {verb['avg_concise_score']}/10")
    print(f"  Avg verbose answer score: {verb['avg_verbose_score']}/10")
    print(f"  Verbosity bonus:          +{verb['verbosity_bonus']} points")
    print(f"  (unbiased baseline: 0.0 point difference)")

    # Experiment 3
    print(f"\n{'─' * WIDTH}")
    print("Experiment 3: Framing Bias (proxy for self-bias)")
    print("Hypothesis: Standard judge vs strict expert judge give different scores")
    print(f"{'─' * WIDTH}")
    self_b = experiment_self_bias(trials=3)
    print(f"\n  Standard prompt avg score: {self_b['avg_standard_score']}/10")
    print(f"  Expert prompt avg score:   {self_b['avg_expert_score']}/10")
    print(f"  Framing delta:             {self_b['framing_delta']:+.2f} points")
    print(f"  {self_b['note']}")

    # Summary
    print(f"\n{'=' * WIDTH}")
    print("Summary: Bias Magnitudes")
    print(f"{'─' * WIDTH}")
    print(f"  Position bias:  {abs(pos['first_position_win_rate'] - 0.5):.0%} deviation from 50/50")
    print(f"  Verbosity bias: +{verb['verbosity_bonus']:.1f} pts for longer answers (same content)")
    print(f"  Framing bias:   {self_b['framing_delta']:+.2f} pts standard vs strict expert prompt")
    print(f"\n  Consistency rate {pos['consistency_rate']:.0%} — "
          f"{'acceptable' if pos['consistency_rate'] > 0.7 else 'problematic, consider multi-shot'}")
    print(f"{'=' * WIDTH}\n")


if __name__ == "__main__":
    main()
