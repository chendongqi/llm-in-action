"""
AI Eval Article 03 — LLM-as-Judge Bias Experiments

Three controlled experiments to measure real bias magnitudes:

  Experiment 1: Position Bias
    Same two answers, shown in two orders (A→B and B→A).
    If the Judge is unbiased, win rates should be ~50/50 regardless of order.
    We measure: how often does the first answer win vs the second?

  Experiment 2: Verbosity Bias
    A concise correct answer vs a verbose correct answer with the same content.
    If the Judge is unbiased, scores should be equal.
    We measure: score delta (verbose - concise).

  Experiment 3: Self-Bias
    An answer generated by Model A, evaluated by Model A vs Model B.
    We measure: self-evaluation score vs cross-evaluation score.

All experiments use the same domain: technical Q&A about Python.
Each experiment runs multiple trials to reduce noise.

Run:
    conda activate llm_base
    python demo_llm_judge_bias.py
"""

